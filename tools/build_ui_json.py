# Merge mTextConfig from master.json
with open(MASTER_JSON, "r", encoding="utf-8") as f:
    master = json.load(f)

tc = master.get("mTextConfig", {}).get("ml_value[]", {})
merged = dict(BASE_UI)

for k, v in tc.items():
    if not k or not v or k == v:
        continue
    # Skip extremely long story texts or formatted strings with many placeholders if unsuitable for UI
    if len(k) <= 50 and k not in merged:
        merged[k] = v

print(f"Total UI entries in ui.json: {len(merged)}")

with open(UI_JSON_LOCAL, "w", encoding="utf-8") as f:
    json.dump(merged, f, ensure_ascii=False, indent=2)

os.makedirs(os.path.dirname(UI_JSON_GAME), exist_ok=True)
with open(UI_JSON_GAME, "w", encoding="utf-8") as f:
    json.dump(merged, f, ensure_ascii=False, indent=2)

print("Saved ui.json to local and game directories!")
